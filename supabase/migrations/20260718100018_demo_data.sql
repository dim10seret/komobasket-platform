-- =====================================================
-- DEMO SCHEDULE
-- ROUNDS 2 - 14
-- =====================================================

DO $$
DECLARE
    v_season_id UUID := '00000000-0000-0000-0000-000000000002';
    v_venue_id  UUID := '00000000-0000-0000-0000-000000000003';

    teams UUID[] := ARRAY[
        '10000000-0000-0000-0000-000000000001'::uuid,
        '10000000-0000-0000-0000-000000000002'::uuid,
        '10000000-0000-0000-0000-000000000003'::uuid,
        '10000000-0000-0000-0000-000000000004'::uuid,
        '10000000-0000-0000-0000-000000000005'::uuid,
        '10000000-0000-0000-0000-000000000006'::uuid,
        '10000000-0000-0000-0000-000000000007'::uuid,
        '10000000-0000-0000-0000-000000000008'::uuid
    ];

    round_no INTEGER;
    pair_no INTEGER;
    match_no INTEGER := 5;

    home_team UUID;
    away_team UUID;

    tmp UUID;
BEGIN

    FOR round_no IN 2..14 LOOP

        FOR pair_no IN 1..4 LOOP

            home_team := teams[pair_no];
            away_team := teams[9-pair_no];

            INSERT INTO matches(
                id,
                season_id,
                home_team_id,
                away_team_id,
                match_date,
                venue_id,
                status,
                round_number,
                created_at,
                updated_at
            )
            VALUES(
                gen_random_uuid(),
                v_season_id,
                home_team,
                away_team,
                TIMESTAMP '2026-09-05'
                    + ((round_no-1) * INTERVAL '7 days')
                    + ((pair_no-1) * INTERVAL '2 hours'),
                v_venue_id,
                'SCHEDULED',
                round_no,
                NOW(),
                NOW()
            );

            match_no := match_no + 1;

        END LOOP;

        -- Circle Method rotation

        tmp := teams[8];

        teams[8] := teams[7];
        teams[7] := teams[6];
        teams[6] := teams[5];
        teams[5] := teams[4];
        teams[4] := teams[3];
        teams[3] := teams[2];
        teams[2] := tmp;

    END LOOP;

END $$;

